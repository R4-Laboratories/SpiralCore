use spiralcore_transfer::{dag::Graph, protocol::Frame};

#[test]
fn exact_sha_profile_preserves_length_and_all_byte_edits() {
    let source: Vec<u8> = (0..8193).map(|i| (i * 71) as u8).collect();
    let mut cases = vec![
        vec![],
        vec![0],
        b"a".to_vec(),
        b"a\0".to_vec(),
        source.clone(),
    ];
    let mut inserted = source.clone();
    inserted.insert(0, 99);
    cases.push(inserted);
    let mut truncated = source.clone();
    truncated.truncate(32);
    cases.push(truncated);
    for input in cases {
        let graph = Graph::fold(&input, 262144).unwrap();
        assert_eq!(graph.rebuild().unwrap(), input);
        assert_eq!(
            spiralcore_transfer::dag::Manifest::decode(&graph.manifest.encode()).unwrap(),
            graph.manifest
        );
        for node in graph.nodes.values() {
            assert_eq!(
                spiralcore_transfer::dag::Node::decode(&node.encode()).unwrap(),
                *node
            );
        }
    }
    assert_ne!(
        Graph::fold(b"a", 100).unwrap().manifest.object,
        Graph::fold(b"a\0", 100).unwrap().manifest.object
    );
}

#[test]
fn profile_rejects_missing_corrupt_scale_and_padding() {
    let mut graph = Graph::fold(b"abc", 100).unwrap();
    let id = graph.manifest.roots[0].1;
    let mut record = graph.nodes[&id].encode();
    record[35] ^= 1;
    assert!(spiralcore_transfer::dag::Node::decode(&record).is_err());
    graph.nodes.remove(&id);
    assert!(graph.rebuild().is_err());
    let full = Graph::fold(&[9; 32], 100).unwrap();
    let mut bad = full.clone();
    bad.manifest.len = 3;
    bad.manifest.object = spiralcore_transfer::object_id(&[9; 3]);
    assert!(bad.rebuild().is_err());
}

#[test]
fn framing_is_bounded_and_canonical() {
    let frame = Frame {
        kind: 1,
        transfer: [7; 32],
        seq: 0,
        body: vec![4, 5, 6],
    };
    let wire = frame.encode().unwrap();
    assert_eq!(wire.len(), 59);
    assert_eq!(Frame::decode(&wire).unwrap(), frame);
    for n in 0..wire.len() {
        assert!(Frame::decode(&wire[..n]).is_err());
    }
    let mut extended = wire.clone();
    extended.push(0);
    assert!(Frame::decode(&extended).is_err());
    let mut flags = wire.clone();
    flags[9] = 1;
    assert!(Frame::decode(&flags).is_err());
    let mut unknown = wire;
    unknown[8] = 77;
    assert!(Frame::decode(&unknown).is_err());
    assert!(Frame {
        body: vec![0; 65536],
        ..frame
    }
    .encode()
    .is_err());
}

#[test]
fn public_invalid_parent_never_panics() {
    use spiralcore_transfer::dag::{missing, rebuild, Manifest, Node};
    let node = Node::Parent {
        scale: 0,
        children: [[0; 32]; 3],
    };
    let id = node.id();
    let nodes = std::collections::BTreeMap::from([(id, node)]);
    let m = Manifest {
        len: 1,
        object: spiralcore_transfer::object_id(b"a"),
        roots: vec![(0, id)],
    };
    assert_eq!(
        missing(&m, &nodes),
        Err(spiralcore_transfer::Error::Integrity)
    );
    assert_eq!(
        rebuild(&m, &nodes),
        Err(spiralcore_transfer::Error::Integrity)
    );
}

#[test]
fn independent_sha256_binary_vectors_are_stable() {
    // Independently constructed with Python hashlib/struct, not generated by this implementation.
    let g = Graph::fold(b"abc", 100).unwrap();
    assert_eq!(
        spiralcore_transfer::hex(&g.manifest.object),
        "11da6f4c13a7fb4564eaf92e2efc5b80cd711442617ee79c3db4a44603251b69"
    );
    assert_eq!(
        spiralcore_transfer::hex(&g.manifest.roots[0].1),
        "1c871e35b70a765d0bdfddaa1e005c736d53ed2b5305a218fa62674304ebe63b"
    );
    assert_eq!(
        spiralcore_transfer::hex(&g.manifest.id()),
        "1c0b6dd2909fb51613fdd1808a02b4f00f7918a880712d40c3a1b657026b75a3"
    );
    let encoded = g
        .manifest
        .encode()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect::<String>();
    assert_eq!(encoded,"0100030000000000000011da6f4c13a7fb4564eaf92e2efc5b80cd711442617ee79c3db4a44603251b6901001c871e35b70a765d0bdfddaa1e005c736d53ed2b5305a218fa62674304ebe63b");
}
